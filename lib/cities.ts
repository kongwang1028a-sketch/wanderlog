export function countryOptions() {
  const map = new Map<string, string>()
  for (const item of CITIES) map.set(item.code, item.country)
  return [...map.entries()]
    .map(([code, name]) => ({ code, name }))
    .sort((a, b) => a.name.localeCompare(b.name, "zh-Hant"))
}

